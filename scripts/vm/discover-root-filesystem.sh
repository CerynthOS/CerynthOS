#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=scripts/vm/cerynth-vm-common.sh
source "$ROOT_DIR/scripts/vm/cerynth-vm-common.sh"

OUTPUT="$ROOT_DIR/vm/root-filesystem.env"
require_vm_key
require_vm_reachable

printf '[cerynth-root-discovery] querying guest root filesystem\n'
ROOT_DEVICE="$(vm_ssh 'findmnt -n -o SOURCE /')"
ROOT_DEVICE="$(vm_ssh "readlink -f '$ROOT_DEVICE'")"
ROOT_UUID="$(vm_ssh "sudo blkid -s UUID -o value '$ROOT_DEVICE'")"

[[ -n "$ROOT_DEVICE" ]] || die "could not discover root device"
[[ -n "$ROOT_UUID" ]] || die "could not discover root UUID"

cat > "$OUTPUT" <<EOF
# Generated by scripts/vm/discover-root-filesystem.sh
# Machine-specific; never commit this file.
CERYNTH_ROOT_DEVICE=$ROOT_DEVICE
CERYNTH_ROOT_UUID=$ROOT_UUID
EOF

printf '\nRoot filesystem discovered:\n'
printf '  Device: %s\n' "$ROOT_DEVICE"
printf '  UUID:   %s\n' "$ROOT_UUID"
printf '  Config: %s\n' "$OUTPUT"
